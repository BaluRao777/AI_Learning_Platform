"""Write docs/after_phase1/COMPARISON.md from the saved baseline and after-Phase-1 responses.

    python backend/scripts/make_comparison.py
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
BEFORE = os.path.join(ROOT, "docs", "baseline")
AFTER = os.path.join(ROOT, "docs", "after_phase1")
COMBOS = [("school", "learn"), ("school", "exam"), ("college", "learn"), ("college", "exam")]


def load(folder, topic, level, mode):
    with open(os.path.join(folder, f"{topic.lower()}_{level}_{mode}.json"), encoding="utf-8") as fh:
        return json.load(fh)


def cell(text, limit=420):
    text = " ".join(str(text).split()).replace("|", "/")
    return text if len(text) <= limit else text[:limit] + " …"


def main():
    lines = ["# Phase 1 comparison: baseline vs. Input Analysis Layer", "",
             "Generated by `backend/scripts/make_comparison.py` from the JSON files in `docs/baseline/` and "
             "`docs/after_phase1/`. Nothing in this file is hand-written except this header.", ""]
    all_before, all_after, wiki_fallback = [], [], 0
    for topic in ("Earth", "Photosynthesis"):
        lines += [f"## {topic}", "", "### Explanation text returned by `/generate`", "",
                  "| level / mode | baseline explanation | after Phase 1 explanation | identical? |", "|---|---|---|---|"]
        plans = []
        for level, mode in COMBOS:
            before = load(BEFORE, topic, level, mode)["response"]
            after = load(AFTER, topic, level, mode)["response"]
            plans.append(after["analysis"])
            all_before.append(before["explanation"])
            all_after.append(after["explanation"])
            if after["subtopics"][0]["title"].startswith("Definition of "):
                wiki_fallback += 1
            same = "yes" if before["explanation"] == after["explanation"] else "no"
            lines.append(f"| {level} / {mode} | {cell(before['explanation'])} | {cell(after['explanation'])} | {same} |")
        lines += ["", "### Teaching plan produced by the analyzer (new `analysis` key)", "",
                  "| level / mode | source | analysis ms | depth | sentences | explanation style | must include | image style |",
                  "|---|---|---|---|---|---|---|---|"]
        for (level, mode), analysis in zip(COMBOS, plans):
            plan = analysis["plan"]
            style = plan["image_style"]
            lines.append(
                f"| {level} / {mode} | {analysis['source']} | {analysis['analysis_ms']} | {plan['depth']} | "
                f"{plan['explanation_length_sentences']} | {cell(plan['explanation_style'], 160)} | "
                f"{cell('; '.join(plan['must_include']), 220)} | {style['type']}, {style['complexity']} |")
        lines.append("")

    lines += ["## Summary (computed)", "",
              f"- Distinct baseline explanations across the 8 requests: **{len(set(all_before))}** (2 topics).",
              f"- Distinct after-Phase-1 explanations across the 8 requests: **{len(set(all_after))}**.",
              f"- After-Phase-1 responses that came from the Wikipedia fallback (Gemini call failed): **{wiki_fallback} of 8**.",
              ""]
    with open(os.path.join(AFTER, "COMPARISON.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print("distinct before", len(set(all_before)), "after", len(set(all_after)), "wiki fallback", wiki_fallback)


if __name__ == "__main__":
    main()
